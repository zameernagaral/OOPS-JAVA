class main{
    public static void main(String[] args){
        int a = 10, b= 20;
        System.out.println("Area of Rectangle = "+(a*b));
        double pi = 3.14;
        System.out.println("Area of Circle = "+(pi*a*a));
        System.out.println("Area of Square = "+(a*a));
        System.out.println("Area of Triangle = "+(0.5*a*b));
    }
}